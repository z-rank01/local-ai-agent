"""Host turn contribution contract."""
from typing import Protocol


class TurnPolicy(Protocol):
    def start(self, history: list[dict]) -> None: ...
    def execution_scope(self) -> set[str] | None: ...
    def stream(self, host, messages: list[dict], session_id: str, conversation_key: str): ...
    async def configure(self, method_id: str, answer_only: bool) -> list[str]: ...
    def checkpoint_state(self, archive): ...
    def restore_state(self, state, load) -> None: ...
    async def verify_restore(self, read_file) -> None: ...
    def allowed_tools(self): ...
    async def completion_events(self, conversation_id: str): ...
    def accept_tool(self, data: dict) -> None: ...
    def checkpoint_event(self, data: dict) -> dict | None: ...
    async def finish_turn(self, conversation_id: str) -> list[dict]: ...
    def has_open_turn(self, conversation_id: str) -> bool: ...
    def before_tool(self, tool: str, arguments: dict) -> dict: ...
    async def after_tool(self, tool: str, result): ...
